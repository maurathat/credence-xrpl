"""Typed refusal codes for the x402 buyer adapter. Every refusal is one stable code plus detail.

Codes are grouped by stage. A refusal never carries prompt text, credentials or response bodies in
its detail; details name the field or value class that failed.

Owner: x402 (X402-P0).
"""

from __future__ import annotations

from enum import Enum


class X402Refusal(Enum):
    # transport and origin
    ORIGIN_NOT_ALLOWED = "ORIGIN_NOT_ALLOWED"
    PAYMENT_MATERIAL_REFUSED = "PAYMENT_MATERIAL_REFUSED"
    HEADER_NOT_ALLOWED = "HEADER_NOT_ALLOWED"
    UNSUPPORTED_METHOD = "UNSUPPORTED_METHOD"
    REDIRECT_REFUSED = "REDIRECT_REFUSED"
    TRANSPORT_FAILED = "TRANSPORT_FAILED"
    MALFORMED_RESPONSE = "MALFORMED_RESPONSE"
    # challenge
    NOT_A_PAYMENT_CHALLENGE = "NOT_A_PAYMENT_CHALLENGE"
    MALFORMED_CHALLENGE = "MALFORMED_CHALLENGE"
    CONTRADICTORY_CHALLENGE = "CONTRADICTORY_CHALLENGE"
    UNSUPPORTED_VERSION = "UNSUPPORTED_VERSION"
    UNSUPPORTED_SCHEME = "UNSUPPORTED_SCHEME"
    UNSUPPORTED_NETWORK = "UNSUPPORTED_NETWORK"
    MALFORMED_AMOUNT = "MALFORMED_AMOUNT"
    MALFORMED_ASSET = "MALFORMED_ASSET"
    MALFORMED_DESTINATION = "MALFORMED_DESTINATION"
    MALFORMED_INVOICE_BINDING = "MALFORMED_INVOICE_BINDING"
    CHALLENGE_EXPIRED = "CHALLENGE_EXPIRED"
    RESOURCE_MISMATCH = "RESOURCE_MISMATCH"
    NO_XRPL_REQUIREMENT = "NO_XRPL_REQUIREMENT"
    # compatibility with Credence's approved execution
    NETWORK_NOT_APPROVED = "NETWORK_NOT_APPROVED"
    MAINNET_READ_ONLY = "MAINNET_READ_ONLY"
    ASSET_NOT_APPROVED = "ASSET_NOT_APPROVED"
    ISSUER_NOT_APPROVED = "ISSUER_NOT_APPROVED"
    AMOUNT_NOT_REPRESENTABLE = "AMOUNT_NOT_REPRESENTABLE"
    CROSS_CURRENCY_UNSUPPORTED = "CROSS_CURRENCY_UNSUPPORTED"
    FACILITATOR_KIND_UNSUPPORTED = "FACILITATOR_KIND_UNSUPPORTED"
    MULTISIGNATURE_UNSUPPORTED = "MULTISIGNATURE_UNSUPPORTED"
    MULTISIGNATURE_UNKNOWN = "MULTISIGNATURE_UNKNOWN"
    INVOICE_BINDING_NOT_IN_X1_TEMPLATE = "INVOICE_BINDING_NOT_IN_X1_TEMPLATE"
    SUBMISSION_NOT_AUTHORIZED = "SUBMISSION_NOT_AUTHORIZED"
    # discovery
    SERVICE_UNVERIFIED = "SERVICE_UNVERIFIED"
    ENDPOINT_CHANGED = "ENDPOINT_CHANGED"
    MALFORMED_DIRECTORY = "MALFORMED_DIRECTORY"
    # procurement and proposal
    POLICY_REJECTED = "POLICY_REJECTED"
    DUPLICATE_INVOICE = "DUPLICATE_INVOICE"
    PROPOSAL_REPLAYED = "PROPOSAL_REPLAYED"
    PURCHASE_ALREADY_AUTHORIZED = "PURCHASE_ALREADY_AUTHORIZED"
    TRANSACTION_ALREADY_BOUND = "TRANSACTION_ALREADY_BOUND"
    CORE_DECISION_MISMATCH = "CORE_DECISION_MISMATCH"
    PROVIDER_NAMESPACE = "PROVIDER_NAMESPACE"
    AGENT_MISMATCH = "AGENT_MISMATCH"
    BINDING_ALTERED = "BINDING_ALTERED"
    # lifecycle
    ILLEGAL_TRANSITION = "ILLEGAL_TRANSITION"
    SETTLEMENT_RESPONSE_MISMATCH = "SETTLEMENT_RESPONSE_MISMATCH"
    PAYMENT_EVIDENCE_MISMATCH = "PAYMENT_EVIDENCE_MISMATCH"
    PAYMENT_EVIDENCE_UNAUTHENTICATED = "PAYMENT_EVIDENCE_UNAUTHENTICATED"
    DELIVERY_UNBOUND = "DELIVERY_UNBOUND"


class X402Refused(Exception):
    """The adapter refuses an input or step. `code` is stable; `detail` is non-sensitive text."""

    def __init__(self, code: X402Refusal, detail: str = "") -> None:
        super().__init__(f"{code.value}: {detail}" if detail else code.value)
        self.code = code
        self.detail = detail
