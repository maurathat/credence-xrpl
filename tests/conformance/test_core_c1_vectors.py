"""Credence Core C1 conformance: the committed vectors in vectors/c1/ against the live code.

The vectors were generated by vectors/build_c1_vectors.py through the real pinned Kessai serializer
(JCS (RFC 8785) + NFC) and frozen. These tests recompute every result and also check each expected
digest against hashlib directly, so a frozen digest cannot drift from its own canonical bytes.
"""

import hashlib
import json
from pathlib import Path
from typing import Any

import pytest

from credence.core import kessai, objects
from credence.core.primitives import DomainError

VECTORS = Path(__file__).resolve().parents[2] / "vectors" / "c1"
MANIFEST = {name: sha for sha, name in json.loads((VECTORS / "MANIFEST.json").read_text())}
CLASSES = {cls.__name__: cls for cls in objects.OBJECT_TYPES}


def _load(name: str) -> dict[str, Any]:
    vector: dict[str, Any] = json.loads((VECTORS / name).read_text(encoding="ascii"))
    return vector


ALL = sorted(MANIFEST)


def _class(vector: dict[str, Any]) -> type[objects.CanonicalObject]:
    _, class_name, _ = vector["entry"].split(".")
    return CLASSES[class_name]


def test_manifest_matches_files_exactly() -> None:
    on_disk = {p.name for p in VECTORS.glob("*.json")} - {"MANIFEST.json"}
    assert on_disk == set(MANIFEST)
    for name, sha in MANIFEST.items():
        assert hashlib.sha256((VECTORS / name).read_bytes()).hexdigest() == sha, name


def test_every_object_type_has_a_positive_vector() -> None:
    positive = {
        _class(v).__name__
        for v in map(_load, ALL)
        if v["entry"].startswith("objects.") and "reject" not in v["expected"]
    }
    assert positive == set(CLASSES)


@pytest.mark.parametrize(
    "vector_id",
    [
        "serializer-nfc-value",
        "serializer-nfc-member-name",
        "serializer-non-ascii-key-order",
        "serializer-large-integers",
        "quote-large-integers",
        "quote-basic",
        "execution_profile-full",
        "execution_profile-not-asserted",
        "serializer-array-order",
        "decision_record-accept",
        "procurement_class-basic",
        "reject-unsorted-set",
        "reject-float-money",
        "reject-bool-as-integer",
        "serializer-reject-python-float",
    ],
)
def test_required_boundary_is_covered(vector_id: str) -> None:
    assert f"{vector_id}.json" in MANIFEST


@pytest.mark.parametrize("name", ALL)
def test_vector(name: str) -> None:
    vector = _load(name)
    expected = vector["expected"]
    entry = vector["entry"]

    if "reject" in expected:
        want = expected["reject"]
        if entry.startswith("objects."):
            with pytest.raises(DomainError) as domain_exc:
                _class(vector).from_canonical(vector["input"])
            assert {"reason": domain_exc.value.reason, "field": domain_exc.value.field} == want
        else:
            with pytest.raises(kessai.SerializationRejected) as ser_exc:
                if entry == "kessai.canonicalize_json_bytes":
                    kessai.canonicalize_json_bytes(vector["input_json_text"].encode())
                else:
                    kessai.canonicalize(vector["input"])
            assert {"reason": ser_exc.value.reason} == want
        return

    canonical = bytes.fromhex(expected["canonical_hex"])
    assert canonical.decode("utf-8") == expected["canonical_text"]
    assert "sha256:" + hashlib.sha256(canonical).hexdigest() == expected["digest"]

    if entry == "kessai.canonicalize_json_bytes":
        form = kessai.canonicalize_json_bytes(vector["input_json_text"].encode())
    elif entry == "kessai.canonicalize":
        form = kessai.canonicalize(vector["input"])
    else:
        obj = _class(vector).from_canonical(vector["input"])
        assert obj.to_canonical() == vector["input"]
        assert obj.digest().value == expected["digest"]
        # The canonical bytes parse back to an equal object.
        assert _class(vector).from_canonical(json.loads(canonical)) == obj
        form = obj.canonical_form()
    assert form.data == canonical
    assert "sha256:" + form.sha256_hex == expected["digest"]
